"""Alembic environment for the Insumap schema.

The connection URL comes from DATABASE_URL_MIGRATOR, falling back to
DATABASE_URL. Migrations are hand-written SQL, so there is no ORM metadata and
nothing is autogenerated. Each migration runs in its own transaction, and the
version table lives in the public schema.
"""

import os
from logging.config import fileConfig

from alembic import context
from sqlalchemy import engine_from_config, pool

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = None
VERSION_TABLE_SCHEMA = "public"


def _migrator_url() -> str:
    url = os.environ.get("DATABASE_URL_MIGRATOR") or os.environ.get("DATABASE_URL")
    if not url:
        msg = (
            "Define DATABASE_URL_MIGRATOR (or DATABASE_URL) before running migrations."
        )
        raise RuntimeError(msg)
    if url.startswith("postgresql://"):
        url = "postgresql+psycopg://" + url.removeprefix("postgresql://")
    return url


def run_migrations_offline() -> None:
    context.configure(
        url=_migrator_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        transaction_per_migration=True,
        version_table_schema=VERSION_TABLE_SCHEMA,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = engine_from_config(
        {"sqlalchemy.url": _migrator_url()},
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    with connectable.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            transaction_per_migration=True,
            version_table_schema=VERSION_TABLE_SCHEMA,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
