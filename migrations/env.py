"""Alembic environment for the Insumap schema.

The connection URL comes from DATABASE_URL_MIGRATOR, falling back to
DATABASE_URL. Migrations are hand-written SQL, so there is no ORM metadata and
nothing is autogenerated. Each migration runs in its own transaction, and the
version table lives in the public schema.

Objects belong to insumap_migrator (Modelo de datos, section 5). When the
connection uses another login (the local superuser or the Neon owner) that may
act as insumap_migrator, the session switches to that role before migrating.
The first revision creates the role and makes the same switch for the rest of
its own run.
"""

import os
from logging.config import fileConfig

from alembic import context
from sqlalchemy import Connection, engine_from_config, pool, text

config = context.config

if config.config_file_name is not None:
    fileConfig(config.config_file_name)

target_metadata = None
VERSION_TABLE_SCHEMA = "public"
OWNER_ROLE = "insumap_migrator"

# The switch only happens once the first revision granted the owner role its
# privileges on the version table; before that, the bootstrap login migrates.
_CAN_ACT_AS_OWNER = text(
    """
    SELECT CASE
             WHEN current_user = :role THEN false
             WHEN NOT pg_has_role(current_user, :role, 'SET') THEN false
             WHEN to_regclass('public.alembic_version') IS NULL THEN false
             ELSE has_table_privilege(:role, 'public.alembic_version', 'UPDATE')
           END
      FROM pg_roles
     WHERE rolname = :role
    """
)


def _migrator_url() -> str:
    url = os.environ.get("DATABASE_URL_MIGRATOR") or os.environ.get("DATABASE_URL")
    if not url:
        msg = (
            "Define DATABASE_URL_MIGRATOR (or DATABASE_URL) before running migrations."
        )
        raise RuntimeError(msg)
    if url.startswith("postgresql://"):
        url = "postgresql+psycopg://" + url.removeprefix("postgresql://")
    return url


def _act_as_owner(connection: Connection) -> None:
    """Switch the session to the owner role when the login may act as it."""
    if connection.execute(_CAN_ACT_AS_OWNER, {"role": OWNER_ROLE}).scalar():
        connection.execute(text(f"SET ROLE {OWNER_ROLE}"))
    connection.commit()


def run_migrations_offline() -> None:
    context.configure(
        url=_migrator_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        transaction_per_migration=True,
        version_table_schema=VERSION_TABLE_SCHEMA,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    connectable = engine_from_config(
        {"sqlalchemy.url": _migrator_url()},
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    with connectable.connect() as connection:
        _act_as_owner(connection)
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            transaction_per_migration=True,
            version_table_schema=VERSION_TABLE_SCHEMA,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
